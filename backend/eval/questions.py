"""
The forty evaluation questions, written by hand.

Section 8 of the guide asks for forty questions across four types, and
asks me to be able to defend how each one was chosen. So every question
carries a "why" line, and none of them were generated by a model. A test
set written by the same kind of system being tested is not a test set.

The split, and what each type is really asking:

**eligibility (12)** turns on a categorical rule: category, state,
gender or course level. The student is clearly inside or clearly
outside. These check that the filter uses the right columns at all.

**threshold (12)** turns on a number, and every profile sits within a
hair of the cutoff. They come in pairs: the same student either side of
the line, differing by half a percent, twenty thousand rupees or one
year. This is the point of the whole project. "minimum 80%" and the
number 79.5 read almost identically to an embedding, so a system that
retrieves by meaning gets these near chance. A system that subtracts
gets them all.

**detail (8)** asks for documents, amounts, deadlines and how to apply.
No arithmetic. These are the questions ordinary RAG is already good at,
and they are here to catch a hybrid system that won the threshold
questions by breaking everything else.

**trap (8)** has no answer in this corpus. Every one names something
real that a student might plausibly ask about and that I deliberately
did not collect. The only correct behaviour is to refuse. Without these
the abstention numbers would be meaningless, because a system that never
refuses would look perfect.

Ground truth for expected_scheme_ids was read off the criteria table by
hand, scheme by scheme. Worth being honest about what that means: for
the hybrid path, retrieval hit rate is partly true by construction,
since both the filter and I are reading the same extracted columns. The
numbers that are not circular, and the ones to actually judge this on,
are answer correctness, threshold accuracy and the abstention pair.
"""

